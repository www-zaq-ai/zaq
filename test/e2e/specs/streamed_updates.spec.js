const { test, expect } = require("@playwright/test")
const { gotoBackOfficeLive, loginToBackOffice, resetE2EState, waitForLiveViewConnected, waitForLiveViewSettled } = require("../support/bo")

test.describe("Connector streamed-update preferences", () => {
  test.beforeEach(async ({ page, request }) => {
    await resetE2EState(request)
    await loginToBackOffice(page)
  })

  test("native connector Edit modals retain and isolate streamed-update preferences", async ({ page }) => {
    await gotoBackOfficeLive(page, "/bo/channels/retrieval/mattermost")
    const suffix = `${test.info().project.name}-${Date.now()}`
    const names = [`Stream workspace A ${suffix}`, `Stream workspace B ${suffix}`]

    for (const name of names) {
      await page.locator("#new-config-button").click()
      const modal = page.locator("#channel-config-modal")
      await expect(modal.locator('details[id^="stream-updates-"]')).toHaveCount(0)
      await modal.locator('input[name="form[name]"]').fill(name)
      await modal.locator('input[name="form[url]"]').fill("https://mattermost.example.test")
      await modal.locator('input[name="form[token]"]').fill("synthetic-stream-test-token")
      await modal.locator("#form_enabled").uncheck()
      await modal.locator('button[type="submit"][form="config-form"]').click()
      await expect(modal).toBeHidden()
    }

    const first = page.locator('[id^="config-card-"]').filter({ hasText: names[0] })
    await first.locator('[id^="edit-config-"]').click()
    const modal = page.locator("#channel-config-modal")
    const settings = modal.locator('details[id^="stream-updates-"]')
    await settings.locator("summary").click()
    await modal.locator('input[name="form[name]"]').fill(`Discarded native ${suffix}`)
    await settings.getByLabel("Enable streamed message updates", { exact: true }).uncheck()
    await waitForLiveViewSettled(page)
    await modal.getByRole("button", { name: "Cancel", exact: true }).click()
    await expect(first).toBeVisible()
    await first.locator('[id^="edit-config-"]').click()
    await settings.locator("summary").click()
    await expect(modal.locator('input[name="form[name]"]')).toHaveValue(names[0])
    await expect(settings.getByLabel("Enable streamed message updates", { exact: true })).toBeChecked()
    await expect(settings).toContainText("Progress/status messages are unaffected")
    await expect(settings).toContainText("When off, selected events can trigger updates without a minimum time interval.")
    await expect(settings.locator('input[name="live_updates[triggers][status]"]')).toHaveCount(0)
    await expect(modal.getByRole("button", { name: "Save streamed updates", exact: true })).toHaveCount(0)
    await expect(modal.locator("form")).toHaveCount(1)
    await expect(page.locator("form form")).toHaveCount(0)
    await modal.locator('input[name="form[name]"]').fill(`${names[0]} renamed`)
    await settings.getByLabel("Minimum streamed-update interval (ms)").fill("250")
    await waitForLiveViewSettled(page)
    await settings.getByLabel("Tool activity", { exact: true }).uncheck()
    await waitForLiveViewSettled(page)
    await settings.getByLabel("Enable streamed message updates", { exact: true }).uncheck()
    await expect(settings.getByLabel("Minimum streamed-update interval (ms)")).toBeDisabled()
    await modal.locator('button[type="submit"][form="config-form"]').click()
    await expect(modal).toBeHidden()
    await page.reload()
    await waitForLiveViewConnected(page)
    await waitForLiveViewSettled(page)
    await first.locator('[id^="edit-config-"]').click()
    await settings.locator("summary").click()
    await expect(modal.locator('input[name="form[name]"]')).toHaveValue(`${names[0]} renamed`)
    await expect(settings.getByLabel("Enable streamed message updates", { exact: true })).not.toBeChecked()
    await expect(settings.getByLabel("Minimum streamed-update interval (ms)")).toHaveValue("250")
    await expect(settings.getByLabel("Tool activity", { exact: true })).not.toBeChecked()
    await modal.getByRole("button", { name: "Cancel", exact: true }).click()
    const second = page.locator('[id^="config-card-"]').filter({ hasText: names[1] })
    await second.locator('[id^="edit-config-"]').click()
    await settings.locator("summary").click()
    await expect(settings.getByLabel("Enable streamed message updates", { exact: true })).toBeChecked()
    await expect(settings.getByLabel("Minimum streamed-update interval (ms)")).toHaveValue("100")
    await expect(settings.getByLabel("Tool activity", { exact: true })).toBeChecked()
  })

  test("widget Edit modal saves details and streamed preferences together and Cancel discards drafts", async ({ page }) => {
    await gotoBackOfficeLive(page, "/bo/channels/retrieval/web_widget")
    const suffix = `${test.info().project.name}-${Date.now()}`
    const name = `Stream preferences widget ${suffix}`
    const renamed = `Renamed stream widget ${suffix}`
    await page.locator("#new-widget-config").click()
    const modal = page.locator("#widget-config-modal")
    await modal.locator('input[name="widget[name]"]').fill(name)
    await page.locator("#save-widget-config").click()
    const settings = modal.locator('details[id^="stream-updates-"]')
    await settings.locator("summary").click()
    await modal.locator('input[name="widget[name]"]').fill(`Discarded widget ${suffix}`)
    await settings.getByLabel("Reasoning", { exact: true }).uncheck()
    await waitForLiveViewSettled(page)
    await page.locator("#close-widget-modal").click()
    const card = page.locator('[id^="widget-connector-"]').filter({ hasText: name })
    await expect(card).toBeVisible()
    await card.locator('[id^="edit-widget-"]').click()
    await settings.locator("summary").click()
    await expect(modal.locator('input[name="widget[name]"]')).toHaveValue(name)
    await expect(settings.getByLabel("Reasoning", { exact: true })).toBeChecked()
    await expect(modal.locator("form")).toHaveCount(1)
    await expect(modal.getByRole("button", { name: "Save streamed updates", exact: true })).toHaveCount(0)
    await expect(settings).toContainText("Answer and reasoning text still use internal batching.")
    await expect(page.locator("form form")).toHaveCount(0)
    await modal.locator('input[name="widget[name]"]').fill(renamed)
    await settings.getByLabel("Minimum streamed-update interval (ms)").fill("350")
    await waitForLiveViewSettled(page)
    await settings.getByLabel("Limit streamed update frequency", { exact: true }).uncheck()
    await waitForLiveViewSettled(page)
    await settings.getByLabel("Reasoning", { exact: true }).uncheck()
    await waitForLiveViewSettled(page)
    await expect(modal.locator('input[name="widget[name]"]')).toHaveValue(renamed)
    await page.locator("#save-widget-config").click()
    await expect(page.locator('[id^="widget-connector-"]').filter({ hasText: renamed })).toBeVisible()
    await page.locator("#close-widget-modal").click()
    await page.reload()
    await waitForLiveViewConnected(page)
    await waitForLiveViewSettled(page)
    await page.locator('[id^="widget-connector-"]').filter({ hasText: renamed }).locator('[id^="edit-widget-"]').click()
    await settings.locator("summary").click()
    await expect(settings.getByLabel("Limit streamed update frequency", { exact: true })).not.toBeChecked()
    await expect(settings.getByLabel("Reasoning", { exact: true })).not.toBeChecked()
    await expect(settings.getByLabel("Minimum streamed-update interval (ms)")).toHaveValue("350")
    await expect(settings.getByLabel("Minimum streamed-update interval (ms)")).toBeDisabled()
    await expect(settings).toContainText("Progress/status messages are unaffected")
  })
})
