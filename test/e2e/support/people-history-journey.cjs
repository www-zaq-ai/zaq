const { expect } = require("@playwright/test")
const { waitForLiveViewConnected, waitForLiveViewSettled } = require("./bo")

module.exports = async function historyJourney(page, admin, baseURL, engine, width) {
  const history = admin.locator("#permission-everyone-access_message_history")
  const share = admin.locator("#permission-everyone-share_conversations")
  await history.locator("..").click()
  await expect(history).toHaveAttribute("aria-checked", "true")
  await page.reload()
  await waitForLiveViewConnected(page)
  await page.locator("#people-settings-menu summary").click()
  await page.locator("#people-conversations-link").click()
  await expect(page).toHaveURL(/\/people\/history$/)
  await expect(page.locator("#people-header")).toBeVisible()
  await expect(page.locator("#history-conversations-table")).toBeVisible()
  await expect(page.getByTestId("simple-pagination-range")).toHaveText("1–25 of 27")
  await expect(page.locator("#filter-team, #filter-person, [phx-click=select_all], [phx-click=delete_conversation], [phx-click=archive_conversation]")).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const wrapper = page.locator("#history-conversations-table").locator("..")
  if (width === 390) expect(await wrapper.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
  for (const [status, range] of [["Archived", "1–25 of 26"], ["Active", "1–1 of 1"], ["All", "1–25 of 27"]]) {
    await page.locator("#history-status [data-select-trigger]").click()
    await page.locator(`#history-status [data-select-option="${status}"]`).click()
    await expect(page.getByTestId("simple-pagination-range")).toHaveText(range)
  }
  await page.getByRole("button", { name: "Next →" }).click()
  await expect(page.getByTestId("simple-pagination-range")).toHaveText("26–27 of 27")
  await page.locator("#channel_type [data-select-trigger]").click()
  await page.locator('#channel_type [data-select-option="API"]').click()
  await expect(page.getByTestId("simple-pagination-range")).toHaveText("1–1 of 1")
  await page.getByText(`Browser history ${width}`, { exact: true }).click()
  await expect(page).toHaveURL(/\/people\/conversations\//)
  await expect(page.locator("#people-header")).toBeVisible()
  await expect(page.getByText("Browser history answer", { exact: true })).toBeVisible()
  await expect(page.getByText("notes.txt", { exact: true })).toBeVisible()
  const answer = page.getByTestId("chat-assistant-bubble").filter({ hasText: "Browser history answer" })
  await expect(answer).toHaveCount(1)
  const info = answer.locator('[phx-click="open_message_info_modal"]')
  const messageId = await info.getAttribute("phx-value-id")
  const positive = page.locator(`[phx-value-type="positive"][phx-value-id="${messageId}"]`)
  const negative = page.locator(`[phx-value-type="negative"][phx-value-id="${messageId}"]`)
  await expect(page.locator("[phx-click=open_share_dialog]")).toHaveCount(0)
  await positive.click()
  await expect(positive).toHaveAttribute("data-feedback-active", "true")
  await negative.click()
  await page.locator('#feedback-modal [phx-value-reason="Not factually correct"]').click()
  await page.locator("#feedback-modal-comment").fill("Browser explanation")
  await page.locator("#submit-feedback-button").click()
  await expect(negative).toHaveAttribute("data-feedback-active", "true")
  await expect(page.getByTestId("rating-feedback-note")).toContainText("Browser explanation")
  await info.click()
  await expect(page.getByTestId("message-info-popin")).toBeVisible()
  await page.locator('[phx-click="toggle_trace_details"]').click()
  await expect(page.getByText("Full JSON", { exact: true })).toBeVisible()
  await expect(page.locator('[data-testid^="trace-details-"] pre')).toContainText("trace details")
  const artifactPath = await page.getByTestId("trace-artifact-link").getAttribute("href")
  expect(artifactPath).toMatch(/^\/people\/conversations\//)
  const artifact = await page.request.get(baseURL + artifactPath)
  expect(artifact.status()).toBe(200)
  expect(await artifact.text()).toBe("Browser artifact")
  await page.locator('[phx-click="close_message_info_modal"]').click()
  await page.locator('[phx-click="open_preview_modal"]').click()
  await expect(page.locator("#file-preview-modal")).toContainText("Authorized source material")
  await page.locator('#file-preview-modal button[phx-click="close_preview_modal"]').click()
  await page.getByRole("link", { name: "← Back", exact: true }).click()
  await expect(page.getByTestId("simple-pagination-range")).toHaveText("1–1 of 1")
  expect(new URL(page.url()).searchParams.get("channel_type")).toBe("api")
  await page.getByText(`Browser history ${width}`, { exact: true }).click()
  await expect(negative).toHaveAttribute("data-feedback-active", "true")
  await share.locator("..").click()
  await expect(share).toHaveAttribute("aria-checked", "true")
  await page.reload()
  await waitForLiveViewConnected(page)
  await page.locator('[phx-click="open_share_dialog"]').click()
  await page.getByRole("button", { name: "Create Link", exact: true }).click()
  const link = await page.locator("[data-share-url]").getAttribute("data-share-url")
  expect(link).toContain("/s/")
  const tokenPath = new URL(link).pathname
  const publicContext = await page.context().browser().newContext()
  const publicPage = await publicContext.newPage()
  await publicPage.goto(baseURL + tokenPath)
  await expect(publicPage.getByText("Browser history answer", { exact: true })).toBeVisible()
  const privateArtifact = await publicPage.request.get(baseURL + artifactPath, { maxRedirects: 0 })
  expect(privateArtifact.status()).toBe(302)
  expect(privateArtifact.headers().location).toBe("/people/login")
  await publicPage.goto(`${baseURL}/people/history`)
  await expect(publicPage).toHaveURL(/\/people\/login$/)
  page.once("dialog", dialog => dialog.accept())
  await page.getByRole("button", { name: "Revoke", exact: true }).click()
  await expect(page.locator("[data-share-url]")).toHaveCount(0)
  await publicPage.goto(baseURL + tokenPath)
  await expect(publicPage.getByText("Browser history answer", { exact: true })).toHaveCount(0)
  await publicContext.close()
  await share.locator("..").click()
  await expect(share).toHaveAttribute("aria-checked", "false")
  await page.locator("#people-settings-menu summary").click()
  await expect(page.locator("#people-conversations-link")).toBeVisible()
  await page.screenshot({ path: `test/e2e/test-results/people-history-${engine}-${width}.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await history.locator("..").click()
  await expect(history).toHaveAttribute("aria-checked", "false")
  await positive.click()
  await expect(page).toHaveURL(/\/people\/profile$/)
  await waitForLiveViewConnected(page)
  await waitForLiveViewSettled(page)
  await expect(page.locator("#people-conversations-link")).toHaveCount(0)
}
