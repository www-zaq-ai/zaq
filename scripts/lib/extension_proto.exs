defmodule Zaq.Scripts.ExtensionProto do
  @moduledoc "Reproducible Extension wire bindings; used only by developer tooling and its CI check."

  alias Google.Protobuf.FileDescriptorSet
  alias Protobuf.Protoc.{CLI, Context, Generator}

  @root Path.expand("../..", __DIR__)
  @prefix [:Zaq, :Engine, :Extension, :Rpc]
  @header "# Generated by scripts/generate_extension_proto.exs; do not edit.\n"

  @doc "Generates bindings, or checks for drift without writing when `check: true`."
  @spec run(keyword()) :: :ok
  def run(opts \\ []) do
    schema_dir = Keyword.get(opts, :schema_dir, Path.join(@root, "priv/proto"))
    output_dir = Keyword.get(opts, :output_dir, Path.join(@root, "lib/zaq/engine/extension/rpc"))
    compiler = compiler!(Keyword.get(opts, :protoc, "protoc"))

    staging =
      Path.join(
        System.tmp_dir!(),
        "zaq-proto-#{System.pid()}-#{System.unique_integer([:positive])}"
      )

    File.mkdir!(staging)

    try do
      generated = generate!(compiler, schema_dir, staging)
      existing = existing!(output_dir)

      changed =
        (Map.keys(generated) ++ Map.keys(existing))
        |> Enum.uniq()
        |> Enum.sort()
        |> Enum.filter(&(Map.get(generated, &1) != Map.get(existing, &1)))

      if Keyword.get(opts, :check, false) do
        if changed != [],
          do:
            Mix.raise(
              "Extension protobuf bindings are stale: #{Enum.join(changed, ", ")}. Run mix run --no-start scripts/generate_extension_proto.exs"
            )
      else
        Enum.each(generated, fn {relative, content} ->
          path = Path.join(output_dir, relative)
          File.mkdir_p!(Path.dirname(path))
          File.write!(path, content)
        end)

        existing
        |> Map.keys()
        |> Enum.reject(&Map.has_key?(generated, &1))
        |> Enum.each(&File.rm!(Path.join(output_dir, &1)))
      end

      :ok
    after
      File.rm_rf!(staging)
    end
  end

  defp compiler!(name) do
    compiler = System.find_executable(name) || Mix.raise("protoc executable not found: #{name}")
    version = @root |> Path.join("priv/proto/protoc.version") |> File.read!() |> String.trim()
    {actual, status} = System.cmd(compiler, ["--version"], stderr_to_stdout: true)

    if status != 0 or String.trim(actual) != "libprotoc #{version}" do
      Mix.raise("Expected protoc #{version}, got: #{String.trim(actual)}")
    end

    compiler
  end

  defp generate!(compiler, schema_dir, staging) do
    files = schema_dir |> Path.join("**/*.proto") |> Path.wildcard() |> Enum.sort()
    if files == [], do: Mix.raise("No Extension protobuf schemas found in #{schema_dir}")
    sources = Enum.map(files, &Path.relative_to(&1, schema_dir))
    descriptor = Path.join(staging, "descriptor.pb")

    {output, status} =
      System.cmd(
        compiler,
        ["-I", schema_dir, "--include_imports", "--descriptor_set_out=#{descriptor}" | sources],
        stderr_to_stdout: true
      )

    if status != 0, do: Mix.raise("protoc failed: #{output}")
    descriptors = descriptor |> File.read!() |> FileDescriptorSet.decode()

    # The locked generator is shared with protoc-gen-elixir; keep its internal API here.
    context =
      %Context{}
      |> CLI.parse_params(
        "plugins=grpc,package_prefix=zaq.engine.extension.rpc,one_file_per_module=true"
      )
      |> CLI.find_types(descriptors.file, sources)

    for descriptor <- descriptors.file, descriptor.name in sources, reduce: %{} do
      generated ->
        {_extensions, files} = Generator.generate(context, descriptor)

        Enum.reduce(files, generated, fn file, acc ->
          file.content
          |> Code.string_to_quoted!()
          |> top_level_modules()
          |> Enum.reduce(acc, &add_module!/2)
        end)
    end
  end

  defp top_level_modules({:__block__, _, modules}), do: modules
  defp top_level_modules(module), do: [module]

  defp add_module!({:defmodule, _, [{:__aliases__, _, segments}, _]} = ast, generated) do
    unless Enum.take(segments, length(@prefix)) == @prefix,
      do: Mix.raise("Unexpected generated module #{inspect(segments)}")

    relative =
      segments
      |> Enum.drop(length(@prefix))
      |> Enum.map(&(&1 |> Atom.to_string() |> Macro.underscore()))
      |> Path.join()

    path = relative <> ".pb.ex"
    if Map.has_key?(generated, path), do: Mix.raise("Generated module path collision: #{path}")

    content =
      @header <>
        (ast |> Macro.to_string() |> Code.format_string!() |> IO.iodata_to_binary()) <> "\n"

    Map.put(generated, path, content)
  end

  defp existing!(directory) do
    case File.lstat(directory) do
      {:ok, %{type: :directory}} -> :ok
      {:error, :enoent} -> :ok
      _ -> Mix.raise("Refusing to replace unowned output path: #{directory}")
    end

    directory
    |> Path.join("**/*")
    |> Path.wildcard(match_dot: true)
    |> Enum.reduce(%{}, fn path, files ->
      case File.lstat!(path).type do
        :directory ->
          files

        :regular ->
          content = File.read!(path)

          unless String.ends_with?(path, ".pb.ex") and String.starts_with?(content, @header),
            do: Mix.raise("Refusing to replace unowned file: #{path}")

          Map.put(files, Path.relative_to(path, directory), content)

        _ ->
          Mix.raise("Refusing to replace unowned path: #{path}")
      end
    end)
  end
end
